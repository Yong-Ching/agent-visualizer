'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { importProject, mentionRegex } = require('../lib/importer.js');
const { writeProject } = require('../lib/writer.js');
const T = require('../public/templates.js');
const G = require('../public/generator.js');

function project(files) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'agentviz-imp-'));
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), text);
  }
  return dir;
}
const agent = (name, description, body) => '---\nname: ' + name + '\ndescription: ' + description + '\ntools: Read, Grep\n---\n' + (body || 'You do the job.') + '\n';
const edgeSet = (r) => r.edges.map((e) => e.from + '>' + e.to + ':' + e.kind).sort();

const DEV_LOOP = {
  '.claude/agents/planner.md': agent('planner', 'Turns one task into a plan with testable acceptance criteria. Use first, before any test or code is written. Read-only.'),
  '.claude/agents/test-writer.md': agent('test-writer', 'Writes failing tests from the acceptance criteria. Use after the plan is approved and before the implementer.'),
  '.claude/agents/implementer.md': agent('implementer', 'Writes production code for one plan step. Use after test-writer has produced failing tests, or to apply a fix that the code-reviewer or the debugger has pinned down.'),
  '.claude/agents/code-reviewer.md': agent('code-reviewer', 'Reviews the diff and returns APPROVE or REJECT with findings. Use after the manager\'s check run passes. Read-only.'),
  '.claude/agents/debugger.md': agent('debugger', 'Finds the root cause of a failing check and proposes a minimal fix. The implementer applies the fix.'),
  '.claude/skills/dev-loop/SKILL.md':
    '---\nname: dev-loop\ndescription: The manager\'s loop.\n---\n| # | Step | Agent |\n|---|---|---|\n| 1 | Plan | `planner` |\n| 2 | Tests first | `test-writer` |\n| 3 | Implement | `implementer` |\n| 4 | Verify | you |\n| 5 | Review | `code-reviewer` |\n',
};

test('reconstructs a dev loop from agent descriptions and a numbered step table', () => {
  const r = importProject(project(DEV_LOOP));
  assert.deepStrictEqual(
    Object.fromEntries(r.agents.map((a) => [a.name, a.role])),
    { 'code-reviewer': 'reviewer', debugger: 'researcher', implementer: 'worker', planner: 'planner', 'test-writer': 'tester' }
  );
  const got = edgeSet(r);
  for (const want of [
    '@main>planner:handoff',
    'planner>test-writer:handoff',
    'test-writer>implementer:handoff',
    'implementer>code-reviewer:handoff',
    'code-reviewer>implementer:fail',
    'code-reviewer>@main:report',
    '@main>debugger:handoff',
    'debugger>implementer:handoff',
  ])
    assert.ok(got.includes(want), 'missing ' + want + ' in ' + got.join(', '));
  assert.ok(!got.some((e) => e.startsWith('implementer>test-writer')), 'no reversed edge');
  for (const e of r.edges) assert.ok(e.evidence.length && e.evidence[0].text, 'every edge carries evidence');
});

test('arrow chains in CLAUDE.md produce a pipeline, and the managed block is ignored', () => {
  const r = importProject(
    project({
      '.claude/agents/researcher-bot.md': agent('researcher-bot', 'Investigates the codebase.'),
      '.claude/agents/builder-bot.md': agent('builder-bot', 'Builds features.'),
      '.claude/agents/qa-checker.md': agent('qa-checker', 'Verifies the result and returns PASS or FAIL.'),
      'CLAUDE.md': '# Flow\n\nresearcher-bot -> builder-bot -> qa-checker. If qa-checker fails, send back to builder-bot.\n\n<!-- agent-visualizer:start -->\nbuilder-bot -> researcher-bot\n<!-- agent-visualizer:end -->\n',
    })
  );
  const got = edgeSet(r);
  assert.ok(got.includes('researcher-bot>builder-bot:handoff'));
  assert.ok(got.includes('builder-bot>qa-checker:handoff'));
  assert.ok(got.includes('@main>researcher-bot:handoff'));
  assert.ok(!got.includes('builder-bot>researcher-bot:handoff'), 'managed block ignored');
});

test('unrelated agents stay unconnected; generic short names need explicit references', () => {
  const r = importProject(
    project({
      '.claude/agents/worker.md': agent('worker', 'Does the work. A worker never reviews.'),
      '.claude/agents/translator.md': agent('translator', 'Translates UI strings into other languages.'),
    })
  );
  assert.deepStrictEqual(r.edges, []);
  assert.ok(!mentionRegex('worker').test('the worker does things'));
  assert.ok(mentionRegex('worker').test('hand it to `worker`'));
  assert.ok(mentionRegex('code-reviewer').test('then the code reviewer checks'));
});

test('a project generated by this tool re-imports its own agents', () => {
  const dir = project({});
  writeProject(dir, T.list.find((t) => t.id === 'simple').design);
  fs.unlinkSync(path.join(dir, '.agent/workflow.json'));
  const r = importProject(dir);
  assert.deepStrictEqual(r.agents.map((a) => a.name).sort(), ['task-planner', 'verifier', 'worker']);
});

test('guessRole prefers the agent name over its description', () => {
  assert.strictEqual(G.guessRole({ name: 'implementer', description: 'Applies fixes the code-reviewer found.' }), 'worker');
  assert.strictEqual(G.guessRole({ name: 'planner', description: 'Writes testable acceptance criteria.' }), 'planner');
  assert.strictEqual(G.guessRole({ name: 'helper', description: 'Reviews pull requests.' }), 'reviewer');
});
