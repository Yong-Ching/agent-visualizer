/*
 * Agent workflow generator.
 * Turns a workflow design (nodes + edges drawn in the GUI) into the files a
 * Claude Code session needs to run that workflow:
 *   .agent/workflow.json              design source of truth (re-open in the GUI)
 *   .agent/WORKFLOW.md                execution playbook the orchestrator follows
 *   .agent/agents/<name>.md           one definition per agent (canonical copy)
 *   .agent/skills/run-agent-workflow/SKILL.md
 *   .agent/session-context.md         injected into every fresh session by a hook
 *   .agent/run.sh                     launcher: starts a fresh session on a task
 *   .claude/agents/<name>.md          mirror so Claude Code can spawn the agents
 *   .claude/skills/run-agent-workflow/SKILL.md  mirror so /run-agent-workflow works
 * plus a managed block in CLAUDE.md and a SessionStart hook in .claude/settings.json
 * (those two are merged into existing files by the writer, never overwritten).
 *
 * Works both in the browser (window.AgentGen) and in Node (require).
 */
