  function slugify(s) {
    return String(s || '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 48) || 'agent';
  }

  function yamlStr(s) {
    return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\s*\n\s*/g, ' ') + '"';
  }

  function firstSentence(s, max) {
    const t = String(s || '').trim().replace(/\s+/g, ' ');
    const m = t.match(/^(.+?[.!?])(\s|$)/);
    let out = m ? m[1] : t;
    if (max && out.length > max) out = out.slice(0, max - 1).trim() + '…';
    return out;
  }

  // Best guess at the role of an agent defined elsewhere, from its name and description.
  function guessRole(a) {
    const rules = [
      [/orchestrat|chief.of.staff|coordinator|manager/, 'custom'],
      [/verif|validat|\bqa\b/, 'verifier'],
      [/review|audit/, 'reviewer'],
      [/test/, 'tester'],
      [/plan|architect/, 'planner'],
      [/research|explor|investigat|search|debug|diagnos/, 'researcher'],
      [/implement|build|develop|engineer|coder|fixer|writer|worker/, 'worker'],
    ];
    // The name is the strongest signal; descriptions often mention other agents' jobs.
    for (const text of [String(a.name || '').toLowerCase(), String(a.description || '').toLowerCase().split(/[.!?]/)[0]]) {
      for (const [re, role] of rules) if (re.test(text)) return role;
    }
    return 'custom';
  }

  function clone(o) {
    return JSON.parse(JSON.stringify(o));
  }

  function mdEscapeCell(s) {
    return String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  }

  // --------------------------------------------------------------- normalize

  function normalize(input) {
    const d = clone(input || {});
    d.version = 1;
    d.name = (d.name || 'Agent workflow').trim();
    d.goal = (d.goal || '').trim();
    d.settings = Object.assign(
      { maxParallel: 4, maxRounds: 3, autoStart: true, runLog: true, mergeWorktrees: true, namePrefix: '' },
      d.settings || {}
    );
    d.settings.maxParallel = Math.max(1, parseInt(d.settings.maxParallel, 10) || 4);
    d.settings.maxRounds = Math.max(1, parseInt(d.settings.maxRounds, 10) || 3);
    d.nodes = Array.isArray(d.nodes) ? d.nodes : [];
    d.edges = Array.isArray(d.edges) ? d.edges : [];

    d.library = Array.isArray(d.library) ? d.library : [];
    const prefix = d.settings.namePrefix ? slugify(d.settings.namePrefix) + '-' : '';
    const used = new Set();
    // Nodes linked to an existing agent file keep their exact name; reserve those first.
    for (const n of d.nodes) {
      n.source = n.source === 'existing' && n.role !== 'orchestrator' ? 'existing' : 'design';
      if (n.source === 'existing') {
        n.name = String(n.name || '').trim();
        used.add(n.name);
      }
    }
    for (const n of d.nodes) {
      n.role = ROLES[n.role] ? n.role : 'custom';
      const r = ROLES[n.role];
      n.label = (n.label || r.title).trim();
      if (n.source !== 'existing') {
        let base = prefix + slugify(n.name || n.label);
        if (base === SKILL_NAME) base += '-agent';
        let name = base;
        let i = 2;
        while (used.has(name)) name = base + '-' + i++;
        used.add(name);
        n.name = name;
      }
      n.description = (n.description || '').trim();
      n.prompt = (n.prompt || '').trim();
      n.skills = Array.isArray(n.skills) ? uniq(n.skills.map((s) => String(s).trim()).filter((s) => /^[A-Za-z0-9:_.-]+$/.test(s))) : [];
      n.color = COLORS.includes(n.color) ? n.color : '';
      n.model = MODELS.includes(n.model) ? n.model : r.model;
      n.tools = Array.isArray(n.tools) ? n.tools.filter((t) => ALL_TOOLS.includes(t)) : r.tools.slice();
      n.isolation = n.isolation === 'worktree' ? 'worktree' : 'none';
      n.perTask = !!n.perTask;
      n.instances = Math.max(1, Math.min(16, parseInt(n.instances, 10) || 1));
      n.background = !!n.background;
    }
    const ids = new Set(d.nodes.map((n) => n.id));
    for (const e of d.edges) {
      e.kind = EDGE_KINDS[e.kind] ? e.kind : 'handoff';
      e.condition = (e.condition || '').trim();
      e.maxIterations = Math.max(1, Math.min(20, parseInt(e.maxIterations, 10) || 3));
    }
    d.edges = d.edges.filter((e) => ids.has(e.from) && ids.has(e.to));
    return d;
  }

  // ------------------------------------------------------------- graph utils

  function byId(d) {
    const m = {};
    for (const n of d.nodes) m[n.id] = n;
    return m;
  }

  function findEntry(d) {
    const orch = d.nodes.find((n) => n.role === 'orchestrator');
    if (orch) return orch;
    const incoming = new Set(d.edges.map((e) => e.to));
    return d.nodes.find((n) => !incoming.has(n.id)) || d.nodes[0] || null;
  }

  function outEdges(d, id) {
    return d.edges.filter((e) => e.from === id);
  }

  function inEdges(d, id) {
    return d.edges.filter((e) => e.to === id);
  }

  // Order nodes by BFS from the entry so the playbook reads top-down.
  function order(d) {
    const entry = findEntry(d);
    if (!entry) return [];
    const seen = new Set([entry.id]);
    const q = [entry.id];
    const out = [];
    const m = byId(d);
    while (q.length) {
      const id = q.shift();
      out.push(m[id]);
      const next = outEdges(d, id)
        .slice()
        .sort((a, b) => (a.kind === 'fail') - (b.kind === 'fail'));
      for (const e of next) if (!seen.has(e.to)) { seen.add(e.to); q.push(e.to); }
    }
    for (const n of d.nodes) if (!seen.has(n.id)) out.push(n);
    return out;
  }

  // A cycle that does not pass through a FAIL edge or the orchestrator has no exit guard.
  function unguardedCycle(d) {
    const entry = findEntry(d);
    const orchId = entry && entry.role === 'orchestrator' ? entry.id : null;
    const adj = {};
    for (const n of d.nodes) adj[n.id] = [];
    for (const e of d.edges) {
      if (e.kind === 'fail' || e.kind === 'report') continue;
      if (e.to === orchId) continue;
      adj[e.from].push(e.to);
    }
    const state = {};
    const stack = [];
    let found = null;
    function dfs(u) {
      state[u] = 1;
      stack.push(u);
      for (const v of adj[u]) {
        if (found) return;
        if (state[v] === 1) { found = stack.slice(stack.indexOf(v)).concat(v); return; }
        if (!state[v]) dfs(v);
      }
      stack.pop();
      state[u] = 2;
    }
    for (const n of d.nodes) if (!state[n.id] && !found) dfs(n.id);
    return found;
  }

  // ---------------------------------------------------------------- validate

  function validate(input) {
    const d = normalize(input);
    const errors = [];
    const warnings = [];
    const m = byId(d);
    if (!d.nodes.length) {
      errors.push('Add at least one agent to the canvas.');
      return { errors, warnings, design: d };
    }
    const orchs = d.nodes.filter((n) => n.role === 'orchestrator');
    if (orchs.length > 1) errors.push('Only one Orchestrator is allowed: the main Claude Code session plays that role. Change the others to another role.');
    if (!orchs.length) warnings.push('No Orchestrator node: the main session will act as an implicit conductor and start at "' + findEntry(d).label + '".');

    const existingNames = {};
    for (const n of d.nodes.filter((x) => x.source === 'existing')) {
      if (!/^[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(n.name)) errors.push('"' + n.label + '" is linked to an existing agent but has no valid agent name.');
      if (existingNames[n.name]) errors.push('Existing agent "' + n.name + '" is on the canvas twice. Use parallel instances instead of a second node.');
      existingNames[n.name] = true;
    }

    const seenPairs = new Set();
    for (const e of d.edges) {
      if (e.from === e.to) errors.push('"' + m[e.from].label + '" is linked to itself. Remove that link.');
      const key = e.from + '>' + e.to + '>' + e.kind;
      if (seenPairs.has(key)) warnings.push('Duplicate ' + e.kind + ' link ' + m[e.from].label + ' → ' + m[e.to].label + '.');
      seenPairs.add(key);
    }

    const entry = findEntry(d);
    const reach = new Set([entry.id]);
    const q = [entry.id];
    while (q.length) {
      const id = q.shift();
      for (const e of outEdges(d, id)) if (!reach.has(e.to)) { reach.add(e.to); q.push(e.to); }
    }
    for (const n of d.nodes) {
      if (!reach.has(n.id)) warnings.push('"' + n.label + '" cannot be reached from "' + entry.label + '", so it will never run.');
      if (!n.description) warnings.push('"' + n.label + '" has no description. It will rely on its role defaults only.');
      const outs = outEdges(d, n.id);
      const hasFail = outs.some((e) => e.kind === 'fail');
      const hasPass = outs.some((e) => e.kind === 'pass');
      if (hasFail && !hasPass && !outs.some((e) => e.kind === 'handoff' || e.kind === 'report'))
        warnings.push('"' + n.label + '" has an on-FAIL link but nothing for PASS. Add an on-PASS (or report) link so the loop can exit.');
      if (hasPass && !hasFail && (n.role === 'verifier' || n.role === 'reviewer'))
        warnings.push('"' + n.label + '" has no on-FAIL link. A failed verdict will be escalated to the orchestrator instead of looping.');
      if (n.role === 'orchestrator' && n.isolation === 'worktree') warnings.push('The orchestrator runs in the main session; worktree isolation on it is ignored.');
      if (n.isolation === 'worktree') {
        const toolsWrite = n.tools.some((t) => t === 'Edit' || t === 'Write' || t === 'Bash');
        if (!toolsWrite) warnings.push('"' + n.label + '" uses a worktree but cannot edit files; isolation is pointless there.');
      }
      if ((n.perTask || n.instances > 1) && n.role !== 'orchestrator') {
        const editing = n.tools.some((t) => t === 'Edit' || t === 'Write');
        if (editing && n.isolation !== 'worktree')
          warnings.push('"' + n.label + '" runs several copies in parallel that can edit files. Consider worktree isolation so they do not overwrite each other.');
      }
    }
    if (d.nodes.some((n) => n.isolation === 'worktree'))
      warnings.push('Worktree isolation requires the target project to be a git repository with at least one commit.');
    const cyc = unguardedCycle(d);
    if (cyc)
      warnings.push(
        'Loop without a guard: ' + cyc.map((id) => m[id].label).join(' → ') +
          '. Mark the back link as "on FAIL" (with max iterations) so it cannot run forever. Until then it is capped at ' + d.settings.maxRounds + ' rounds.'
      );
    return { errors, warnings, design: d };
  }

  // ------------------------------------------------------------- generation

  function mermaid(d) {
    const m = byId(d);
    const lines = ['flowchart LR'];
    for (const n of d.nodes) {
      const badges = [];
      if (n.perTask) badges.push('×per task');
      else if (n.instances > 1) badges.push('×' + n.instances);
      if (n.isolation === 'worktree') badges.push('worktree');
      const text = (n.label + (badges.length ? '<br/><small>' + badges.join(' · ') + '</small>' : '')).replace(/"/g, "'");
      const shape = n.role === 'orchestrator' ? ['(["', '"])'] : n.role === 'verifier' || n.role === 'reviewer' ? ['{{"', '"}}'] : ['["', '"]'];
      lines.push('  ' + safeId(n) + shape[0] + text + shape[1]);
    }
    for (const e of d.edges) {
      const label = e.kind === 'fail' ? 'FAIL ≤' + e.maxIterations : e.kind === 'pass' ? 'PASS' : e.kind === 'report' ? 'report' : '';
      const cond = e.condition ? (label ? label + ': ' : '') + e.condition : label;
      const arrow = e.kind === 'fail' || e.kind === 'report' ? '-.->' : '-->';
      lines.push('  ' + safeId(m[e.from]) + ' ' + arrow + (cond ? '|"' + cond.replace(/"/g, "'") + '"|' : '') + ' ' + safeId(m[e.to]));
    }
    return lines.join('\n');
  }

  function safeId(n) {
    return n.name.replace(/-/g, '_');
  }

  function fanOutText(n, d) {
    if (n.perTask) return 'one instance per work package from the plan, up to ' + d.settings.maxParallel + ' at a time, all in parallel';
    if (n.instances > 1) return n.instances + ' parallel instances (split the work between them)';
    return 'a single instance';
  }

  function edgeRouteText(e, d) {
    const m = byId(d);
    const to = m[e.to];
    const target = to.role === 'orchestrator' ? 'back to you (the orchestrator)' : '**' + to.label + '** (`' + to.name + '`)';
    const cond = e.condition ? ' when ' + e.condition : '';
    switch (e.kind) {
      case 'pass':
        return 'If the verdict is **PASS**' + cond + ' → ' + target + '.';
      case 'fail':
        return (
          'If the verdict is **FAIL**' + cond + ' → ' + target +
          ', passing the full list of issues. Loop guard: at most **' + e.maxIterations +
          '** attempt(s) on this link; when exceeded, stop looping and escalate to the orchestrator with the outstanding issues.'
        );
      case 'report':
        return 'Report' + cond + ' → ' + target + '.';
      default:
        return 'Hand off' + cond + ' → ' + target + '.';
    }
  }

  function agentFile(n, d) {
    const r = ROLES[n.role];
    const m = byId(d);
    const ins = inEdges(d, n.id);
    const outs = outEdges(d, n.id);
    const branching = outs.some((e) => e.kind === 'pass' || e.kind === 'fail') || n.role === 'verifier' || n.role === 'reviewer';
    const descLine = firstSentence(n.description, 220) || r.blurb;
    const fm = ['---', 'name: ' + n.name, 'description: ' + yamlStr(n.label + ' in the "' + d.name + '" workflow. ' + descLine)];
    if (n.tools.length && n.tools.length < ALL_TOOLS.length) fm.push('tools: ' + n.tools.join(', '));
    if (n.model && n.model !== 'inherit') fm.push('model: ' + n.model);
    if (n.skills.length) {
      fm.push('skills:');
      for (const s of n.skills) fm.push('  - ' + s);
    }
    if (n.isolation === 'worktree' && n.role !== 'orchestrator') fm.push('isolation: worktree');
    fm.push('color: ' + (n.color || r.color), '---', '');

    const b = [];
    b.push('<!-- ' + MARKER + ': edit the design in the GUI (or .agent/workflow.json), not this file -->', '');
    b.push('You are **' + n.label + '**, the ' + r.title.toLowerCase() + ' in the "' + d.name + '" multi-agent workflow.', '');
    b.push('## Your job', '', n.description || r.blurb, '');
    if (n.prompt) {
      // A refined / hand-written prompt replaces the generic role guidance.
      b.push('## Instructions', '', n.prompt, '');
    } else if (r.guidance.length) {
      b.push('## How to work', '');
      for (const g of r.guidance) b.push('- ' + g);
      b.push('');
    }
    b.push('## Where you sit in the workflow', '');
    b.push('- You are spawned by the orchestrator (the main Claude Code session). You cannot spawn other agents; the orchestrator routes your output.');
    if (ins.length) b.push('- You receive work from: ' + uniq(ins.map((e) => m[e.from].label)).join(', ') + '.');
    if (ins.some((e) => e.kind === 'fail')) b.push('- You may be re-run with FAIL feedback from ' + uniq(ins.filter((e) => e.kind === 'fail').map((e) => m[e.from].label)).join(', ') + '. When that happens, fix every listed issue.');
    if (outs.length) b.push('- Your output goes to: ' + outs.map((e) => m[e.to].label + ' (' + EDGE_KINDS[e.kind].label + (e.condition ? ', ' + e.condition : '') + ')').join('; ') + '.');
    if (n.isolation === 'worktree') b.push('- You run in your own git worktree. Commit your finished work there with a clear message, so the orchestrator can merge your branch.');
    if (n.perTask || n.instances > 1) b.push('- Other copies of you run in parallel on other packages. Touch only the files in your own scope.');
    b.push('');
    b.push('## Output contract', '');
    if (r.output) b.push(r.output, '');
    if (branching) {
      b.push(
        'End your reply with a verdict line the orchestrator can route on, exactly one of:', '',
        '```', 'VERDICT: PASS', 'VERDICT: FAIL', '```', '',
        'On FAIL, list each issue as `- [severity] file:line: problem → required fix`.', ''
      );
    } else if (!r.output) {
      b.push('Finish with a concise summary of what you did, what you found, and anything the next agent must know.', '');
    }
    return fm.join('\n') + b.join('\n');
  }

  function uniq(a) {
    return Array.from(new Set(a));
  }

  function workflowMd(d) {
    const entry = findEntry(d);
    const orch = entry && entry.role === 'orchestrator' ? entry : null;
    const nodes = order(d);
    const m = byId(d);
    const L = [];
    L.push('<!-- ' + MARKER + ': edit the design in the GUI (or .agent/workflow.json), not this file -->');
    L.push('# Agent workflow: ' + d.name, '');
    L.push(
      'This is the execution playbook for the multi-agent workflow designed for this project. ' +
        'The **main Claude Code session is the orchestrator**' + (orch ? ' ("' + orch.label + '")' : '') +
        ': it reads this file, spawns the agents below with the Agent tool, routes their output along the links, and reports back to the user. ' +
        'Subagents cannot spawn other agents, so every spawn happens here in the main session.',
      ''
    );
    L.push('## Goal', '', d.goal ? d.goal : '_No default goal. Use the task the user gives you (or the arguments to `/' + SKILL_NAME + '`)._', '');
    L.push('## Diagram', '', '```mermaid', mermaid(d), '```', '');

    L.push('## Agents', '', '| Agent | `subagent_type` | Role | Runs as | Isolation | Model | Skills |', '|---|---|---|---|---|---|---|');
    for (const n of nodes) {
      const runs = n.role === 'orchestrator' ? 'main session' : n.perTask ? 'one per package' : n.instances > 1 ? '×' + n.instances + ' parallel' : 'single';
      L.push(
        '| ' + mdEscapeCell(n.label) + ' | ' + (n.role === 'orchestrator' ? '— (you)' : '`' + n.name + '`' + (n.source === 'existing' ? ' (existing)' : '')) + ' | ' + ROLES[n.role].title +
          ' | ' + runs + ' | ' + (n.isolation === 'worktree' && n.role !== 'orchestrator' ? 'git worktree' : '—') + ' | ' + (n.source === 'existing' ? 'as defined' : n.model) +
          ' | ' + (n.skills.length ? n.skills.map((x) => '`' + x + '`').join(', ') : '—') + ' |'
      );
    }
    L.push('');
    if (d.nodes.some((n) => n.source === 'existing'))
      L.push('Agents marked "(existing)" are your own agent definitions, used as they are. They were not written for this workflow, so always tell them in the prompt what output the next step needs (including a `VERDICT: PASS|FAIL` line when their output is routed on a verdict).', '');

    if (orch) {
      L.push('## Your brief as orchestrator', '', orch.description || ROLES.orchestrator.blurb, '');
      for (const g of ROLES.orchestrator.guidance) L.push('- ' + g);
      L.push('');
    }

    L.push('## Execution protocol', '');
    const proto = [
      '**Start a run.** Restate the task in one line.' + (d.settings.runLog ? ' Create `.agent/runs/<YYYYMMDD-HHMM>/log.md` and append one line per step (who ran, verdict, next step). Save the plan there as `plan.md` when one exists.' : ''),
      '**Follow the links, not your instincts.** Start at **' + entry.label + '** and move only along the links described in "Steps" below. Do not skip agents or do their work yourself.',
      '**Spawn with the Agent tool** using `subagent_type` = the agent\'s name. Every prompt must be self-contained: the overall goal, this agent\'s specific assignment, acceptance criteria, and the relevant output of upstream agents (summarised if long, never dropped).',
      '**Parallelism.** When a step fans out (several instances, one per package, or several outgoing handoff links), send all those Agent calls in a single message so they run concurrently, at most ' + d.settings.maxParallel + ' at a time. A step with several incoming handoff links waits until all of them have finished (join).',
      '**Routing on verdicts.** Agents that branch end with `VERDICT: PASS` or `VERDICT: FAIL`. Read that line to choose the PASS or FAIL link. If it is missing, treat it as FAIL with "no verdict given".',
      '**Loop guards.** Keep a counter per FAIL link. When a FAIL link has used up its max iterations, stop looping and escalate: decide whether to re-plan, narrow the scope, or ask the user. Never loop silently. Any other cycle in the graph is capped at ' + d.settings.maxRounds + ' rounds.',
      '**On re-runs after FAIL,** re-spawn only the instances whose work failed, and include the verifier\'s full issue list plus the previous attempt\'s summary in the prompt.',
    ];
    if (d.nodes.some((n) => n.isolation === 'worktree' && n.role !== 'orchestrator')) {
      proto.push(
        '**Worktrees.** For agents marked "git worktree", pass `isolation: "worktree"` to the Agent tool. Each returns the worktree path and branch it worked on. Pass those paths/branches to downstream agents (e.g. the verifier must inspect the worker\'s worktree, not the main checkout). ' +
          (d.settings.mergeWorktrees
            ? 'After the work has passed verification, merge each branch into the current branch (`git merge --no-ff <branch>`), resolve conflicts yourself or with a worker, then run the test suite once more on the merged result. Finally clean up: `git worktree remove <path>` and `git branch -d <branch>` for every merged worktree.'
            : 'Do not merge the branches automatically; list them in the final report for the user to merge.')
      );
    }
    proto.push(
      '**Finish.** When the flow reaches its end (or returns to you), give the user a final report: what was done, verdicts per package, files/branches changed, how it was verified, and anything left open.'
    );
    proto.forEach((p, i) => L.push(i + 1 + '. ' + p));
    L.push('');

    L.push('## Steps', '');
    for (const n of nodes) {
      const outs = outEdges(d, n.id);
      const ins = inEdges(d, n.id);
      if (n.role === 'orchestrator') {
        L.push('### ' + n.label + ' (you, the main session)', '');
        L.push('- Kick-off: understand the task, gather any context you need, then follow the links below.');
        const back = ins.map((e) => m[e.from].label);
        if (back.length) L.push('- Results come back to you from: ' + uniq(back).join(', ') + '. Then decide: done → final report; not done → follow your outgoing links again (counts as a new round, max ' + d.settings.maxRounds + ').');
      } else {
        L.push('### ' + n.label + ' (`' + n.name + '`)', '');
        L.push('- Spawn: `subagent_type: "' + n.name + '"`' + (n.isolation === 'worktree' ? ', `isolation: "worktree"`' : '') + (n.model !== 'inherit' ? ' (model: ' + n.model + ')' : '') + ', ' + fanOutText(n, d) + '.');
        if (n.description) L.push('- Assignment: ' + n.description.replace(/\s*\n\s*/g, ' '));
        const handIns = ins.filter((e) => e.kind !== 'fail');
        if (handIns.length > 1) L.push('- Join: wait for ' + uniq(handIns.map((e) => m[e.from].label)).join(' and ') + ' to finish, then combine their output into the prompt.');
      }
      if (!outs.length && n.role !== 'orchestrator') {
        L.push('- Then: end of the flow. Return to the orchestrator and write the final report.');
      }
      const handoffs = outs.filter((e) => e.kind === 'handoff');
      if (handoffs.length > 1) L.push('- Fan-out: start ' + handoffs.map((e) => m[e.to].label).join(', ') + ' in parallel.');
      for (const e of outs) L.push('- ' + edgeRouteText(e, d));
      if (n.role !== 'orchestrator' && outs.some((e) => e.kind === 'pass') && !outs.some((e) => e.kind === 'fail'))
        L.push('- If the verdict is **FAIL** → escalate to the orchestrator with the issues (no FAIL link was designed).');
      L.push('');
    }

    L.push('## Final report format', '', '```', 'RESULT: <done | partial | blocked>', 'SUMMARY: <2-4 sentences>', 'WORK: <per package: owner agent, verdict, files/branch>', 'VERIFICATION: <commands run and outcomes>', 'OPEN ITEMS: <anything left for the user>', '```', '');
    return L.join('\n');
  }

  function skillMd(d) {
    return [
      '---',
      'name: ' + SKILL_NAME,
      'description: ' + yamlStr('Run the "' + d.name + '" multi-agent workflow designed for this project (agents: ' + d.nodes.filter((n) => n.role !== 'orchestrator').map((n) => n.name).join(', ') + '). Use when the user asks to build, fix, or deliver a task with the agent team, or types /' + SKILL_NAME + ' <task>.'),
      '---',
      '',
      '<!-- ' + MARKER + ' -->',
      '',
      'Run the project\'s designed agent workflow on this task:',
      '',
      '$ARGUMENTS',
      '',
      'Steps:',
      '',
      '1. Read `.agent/WORKFLOW.md` in full. It is the playbook: who to spawn, in what order, how to route verdicts, loop limits, worktree handling.',
      '2. Determine the task: the text above if present; otherwise the Goal in `.agent/WORKFLOW.md`; otherwise ask the user for it in one short question.',
      '3. Act as the orchestrator and execute the workflow exactly as designed, spawning the agents with the Agent tool (`subagent_type` = agent name).',
      '4. Finish with the final report described in the playbook.',
      '',
    ].join('\n');
  }

  function sessionContext(d) {
    const entry = findEntry(d);
    const orch = entry && entry.role === 'orchestrator' ? entry : null;
    const lines = [
      '[agent-visualizer] This project has a designed multi-agent workflow: "' + d.name + '".',
      'In this session you are the orchestrator' + (orch ? ' ("' + orch.label + '"' + (/chief of staff/i.test(orch.label) ? '' : ', chief of staff') + ')' : '') + '. For any task the user asks you to build, change, fix or investigate, do not do the work alone: read .agent/WORKFLOW.md and execute the workflow it describes, spawning the project agents (' +
        d.nodes.filter((n) => n.role !== 'orchestrator').map((n) => n.name).join(', ') + ') with the Agent tool.',
      'Small questions about the project, or the user explicitly asking you to work alone, do not need the workflow.',
    ];
    if (d.goal) {
      lines.push(
        d.settings.autoStart
          ? 'Default task for this project: "' + d.goal.replace(/\s+/g, ' ') + '". If the user\'s first message is a go-ahead (e.g. "go", "start", "run") or empty of any other task, start this task immediately with the workflow.'
          : 'Default task for this project (start it only when the user asks): "' + d.goal.replace(/\s+/g, ' ') + '".'
      );
    }
    lines.push('The user can also start a run explicitly with /' + SKILL_NAME + ' <task>.');
    return lines.join('\n') + '\n';
  }

  function runSh(d) {
    return [
      '#!/usr/bin/env bash',
      '# ' + MARKER,
      '# Start a fresh Claude Code session that runs the "' + d.name.replace(/[\r\n]/g, ' ') + '" agent workflow.',
      '# Usage: .agent/run.sh "describe the task"   (no argument = the workflow\'s default goal)',
      'set -euo pipefail',
      'cd "$(dirname "$0")/.."',
      'exec claude "/' + SKILL_NAME + ' ${*:-}"',
      '',
    ].join('\n');
  }

  function claudeMdBlock(d) {
    return [
      '## Agent workflow (managed by agent-visualizer)',
      '',
      'This project runs work through a designed multi-agent workflow, "' + d.name + '". The main session is the orchestrator.',
      '',
      '- Playbook: `.agent/WORKFLOW.md` (read it before starting any build/fix task and follow it).',
      '- Agents: ' + d.nodes.filter((n) => n.role !== 'orchestrator').map((n) => '`' + n.name + '`').join(', ') + ' (definitions in `.agent/agents/`, mirrored to `.claude/agents/`).',
      '- Start a run: `/' + SKILL_NAME + ' <task>` or `.agent/run.sh "<task>"` from a terminal.',
      '- To change the team, edit the design in the agent-visualizer GUI and regenerate; do not hand-edit generated files.',
    ].join('\n');
  }

  const HOOK_COMMAND = '[ -f "$CLAUDE_PROJECT_DIR/.agent/session-context.md" ] && cat "$CLAUDE_PROJECT_DIR/.agent/session-context.md" || true';

  function generate(input) {
    const v = validate(input);
    const d = v.design;
    const files = {};
    if (v.errors.length) return { files, errors: v.errors, warnings: v.warnings, design: d };

    const designOut = clone(d);
    files['.agent/workflow.json'] = JSON.stringify(designOut, null, 2) + '\n';
    files['.agent/WORKFLOW.md'] = workflowMd(d);
    files['.agent/session-context.md'] = sessionContext(d);
    files['.agent/run.sh'] = runSh(d);
    files['.agent/.gitignore'] = 'runs/\nbackups/\n';
    const skill = skillMd(d);
    files['.agent/skills/' + SKILL_NAME + '/SKILL.md'] = skill;
    files['.claude/skills/' + SKILL_NAME + '/SKILL.md'] = skill;
    for (const n of d.nodes) {
      if (n.source === 'existing') continue; // the user's own agent file is used as-is
      const content = agentFile(n, d);
      if (n.role === 'orchestrator') {
        // The orchestrator is the main session; keep its definition for reference only.
        files['.agent/agents/' + n.name + '.md'] = content;
      } else {
        files['.agent/agents/' + n.name + '.md'] = content;
        files['.claude/agents/' + n.name + '.md'] = content;
      }
    }
    return {
      files,
      errors: [],
      warnings: v.warnings,
      design: d,
      claudeMd: claudeMdBlock(d),
      hook: { event: 'SessionStart', matcher: 'startup|clear', command: HOOK_COMMAND },
    };
  }

  return {
    MARKER,
    SKILL_NAME,
    ALL_TOOLS,
    MODELS,
    COLORS,
    ROLES,
    EDGE_KINDS,
    HOOK_COMMAND,
    slugify,
    guessRole,
    normalize,
    validate,
    generate,
    mermaid,
    findEntry,
  };
